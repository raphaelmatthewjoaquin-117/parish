CREATE OR REPLACE FUNCTION public.set_service_request_active_slot_key() RETURNS trigger

LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$

BEGIN

    IF NEW."Status" IN ('PendingVerification', 'PendingReview', 'Confirmed') AND NEW."ScheduledDate" IS NOT NULL AND NEW."ScheduledTime" IS NOT NULL THEN

        NEW."ActiveSlotKey" := NEW."ServiceId"::text || '|' || to_char(NEW."ScheduledDate", 'YYYY-MM-DD') || '|' || to_char(NEW."ScheduledTime", 'HH24:MI:SS');

    ELSE

        NEW."ActiveSlotKey" := NULL;

    END IF;

    RETURN NEW;

END;

$$;

CREATE TRIGGER "trg_ServiceRequest_ActiveSlotKey" BEFORE INSERT OR UPDATE ON "public"."ServiceRequest" FOR EACH ROW EXECUTE FUNCTION public.set_service_request_active_slot_key();

